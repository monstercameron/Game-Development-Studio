export function modelCatalogDefinitions() {
  return modelCatalog.map((model) => ({ role: 'model', ...model }));
}

export function buildModelCatalog({
  services = null,
  inventory = null,
  chatService = null,
  managedIds = [],
} = {}) {
  const managed = new Set(managedIds);
  // These are the IDs currently accepted by the guarded removal endpoint.
  const removable = new Set([
    'tts',
    '3d-hunyuan',
    'segmentation',
    'motion-hy',
    'motion-bricks',
    'asr',
  ]);
  return {
    schemaVersion: 1,
    generatedAt: new Date().toISOString(),
    runtimeAvailable: Array.isArray(services),
    storageScan: inventory
      ? {
          state: inventory.state,
          observedAt: inventory.observedAt || null,
          error: inventory.error || null,
        }
      : null,
    note: 'Service status and file inventory are separate snapshots. A reachable service does not necessarily mean a model is loaded. GPU budgets are estimates; provider-selected cloud models are not enumerated.',
    models: modelCatalogDefinitions().map((model) => {
      const service =
        model.id === 'chat'
          ? chatService
          : services?.find((item) => item.id === (model.serviceId || model.id)) || null;
      const item = inventory?.entries?.find((entry) => entry.id === model.id);
      const storage = item
        ? {
            managed: true,
            installed: item.installed,
            bytes: item.bytes,
            files: item.files,
            path: item.path,
            removable: removable.has(item.id) && item.removable !== false,
            error: item.error || null,
          }
        : inventory
          ? {
              managed: managed.has(model.id),
              installed: null,
              bytes: null,
              files: null,
              path: null,
              removable: false,
              error: null,
            }
          : null;
      return { ...model, service: service || null, storage };
    }),
  };
}
